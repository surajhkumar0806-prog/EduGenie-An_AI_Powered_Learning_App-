import time
from google import genai

PRIMARY_MODEL = "gemini-3.8-flash"
FALLBACK_MODEL = "gemini-2.5-flash"


def generate_with_retry(client: genai.Client, prompt: str, retries: int = 3) -> str:
    last_error = None
    for model in (PRIMARY_MODEL, FALLBACK_MODEL):
        for attempt in range(retries):
            try:
                chat = client.chats.create(model=model)
                response = chat.send_message(prompt)
                if response and response.text:
                    return response.text
                return "No content was generated by the model."
            except Exception as e:
                last_error = e
                msg = str(e)
                if "503" in msg or "UNAVAILABLE" in msg or "429" in msg:
                    time.sleep(2 ** attempt)  # wait 1s, 2s, 4s
                    continue
                break  # other error: try the next model
    raise RuntimeError(f"Gemini is busy, please try again in a minute. ({last_error})")